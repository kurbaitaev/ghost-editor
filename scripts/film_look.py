#!/usr/bin/env python3
"""Apply a film look (Spectral Film LUT .cube + optional film grain and halation) to a clip with ffmpeg.

Two pipelines:
  grain 0 (default for --fast): one full LUT (negative -> print), the fastest path.
  grain > 0: the Spectral Film LUT node tree from its README, rebuilt in ffmpeg:
      [halation] -> negative LUT (ADX) -> + grain (noise plate x per-density grain LUT) -> print LUT
    The grain plate comes from the tool's own grain generator (spectral_film_lut.grain_generation,
    NPS kernel + Gaussian noise), scaled for the simulated frame size, so 1.0 means the stock's
    datasheet RMS granularity on a Super 35 frame. Above 1 it is exaggerated (reels compress grain away).

Usage
  film_look.py list
  film_look.py apply IN OUT --look vision3_500t [--grain 1] [--halation 0.4] [--ss 15.7 --t 3]
  film_look.py apply IN OUT --lut any.cube                       # any 3D LUT, full pipeline only
  film_look.py split IN OUT --look cinestill800t                 # before | after, divider line
  film_look.py still IN OUT.png --look trix400 --at 16.5         # one graded frame

Input is treated as Rec.709 video (prep.sh output). Output: H.264 yuv420p BT.709, audio copied.
Needs: ffmpeg; for grain, the venv with spectral_film_lut (~/.venvs/ghost-looks), else numpy noise.
"""
import argparse
import json
import os
import subprocess
import sys
import threading
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from x264 import THREADS as X264_THREADS  # noqa: E402  (scripts/X264_THREADS)
LUTS = Path(os.environ.get("GHOST_LUTS") or HERE.parent / "library" / "luts")  # generated by gen_luts.py (setup_looks.sh)
SWS = "flags=bicubic+accurate_rnd+full_chroma_int+full_chroma_inp"
TO_RGB = f"scale=in_color_matrix=bt709:in_range=tv:out_range=pc:{SWS},format=gbrp16le"
TO_YUV = f"scale=out_color_matrix=bt709:out_range=tv:{SWS},format=yuv420p"
TAGS = ["-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv"]
FILM_MM = {"35mm": 24.89, "s16": 12.52, "16mm": 10.26, "s8": 5.79, "still35": 36.0}


def lut_path(rel):
    """looks.json paths are relative to the LUT folder (older files carried a luts/ prefix)"""
    rel = rel[5:] if rel.startswith("luts/") else rel
    return LUTS / rel


def looks():
    p = LUTS / "looks.json"
    if not p.exists():
        sys.exit(f"{p} missing: run bash scripts/setup_looks.sh first")
    return json.loads(p.read_text())


def probe(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                          "stream=width,height,r_frame_rate:format=duration", "-of", "json", path],
                         capture_output=True, text=True, check=True).stdout
    j = json.loads(out)
    s = j["streams"][0]
    num, den = s["r_frame_rate"].split("/")
    has_audio = bool(subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a", "-show_entries",
                                     "stream=index", "-of", "csv=p=0", path],
                                    capture_output=True, text=True).stdout.strip())
    return dict(w=int(s["width"]), h=int(s["height"]), fps=float(num) / float(den),
                dur=float(j["format"]["duration"]), audio=has_audio)


def esc(p):
    """Escape a path for an ffmpeg filter argument."""
    return str(p).replace("\\", "/").replace(":", "\\:").replace("'", "\\'").replace(",", "\\,")


def halation_glow(src, dst, w, threshold=0.45, radius=0.04, tint=(1.0, 0.30, 0.05)):
    """Red-orange glow map from the source highlights (light that scatters back off the film base
    and re-exposes the red layer around bright edges). It is screened onto the graded image after the
    print LUT: in front of the LUT the print curve crushes it on night footage."""
    sigma = max(1.0, w * radius / 4)   # the glow is low-frequency: blur at quarter size, scale back up
    lv = f"colorlevels=rimin={threshold}:gimin={threshold}:bimin={threshold}"
    # the red-sensitive layer sits deepest, so the scattered light is the highlights' red channel
    mix = f"colorchannelmixer=rr={tint[0]}:rg=0:rb=0:gr={tint[1]}:gg=0:gb=0:br={tint[2]}:bg=0:bb=0"
    return (f"[{src}]{lv},{mix},scale=iw/4:ih/4:flags=area,gblur=sigma={sigma:.1f}:steps=3,"
            f"scale={w}:-2:flags=bicubic,format=gbrp16le[{dst}];")


class GrainPlate:
    """Feeds a looping grain overlay (mid-grey 0.5 +- noise) into ffmpeg as raw rgb24 frames."""

    def __init__(self, w, h, mono, amp, n_frames, unique=16, frame_mm=24.89, grain_um=6.0, seed=7):
        import numpy as np
        self.np = np
        self.n = n_frames
        scale = max(w, h) / frame_mm  # pixels per mm on the simulated frame
        try:
            from spectral_film_lut.grain_generation import generate_grain
            gen = lambda: generate_grain((h, w, 3), scale, grain_size_mm=grain_um / 1000, bw_grain=mono)
            self.source = "spectral_film_lut.grain_generation.generate_grain"
        except Exception:  # venv without the package: plain Gaussian (identical at sub-pixel grain sizes)
            rng = np.random.default_rng(seed)
            gen = lambda: rng.standard_normal((h, w, 1 if mono else 3), dtype=np.float32)
            self.source = "numpy Gaussian"
        np.random.seed(seed)
        self.frames = []
        for _ in range(unique):
            g = gen()
            if g.shape[-1] == 1:
                g = np.repeat(g, 3, axis=-1)
            # generate_grain_frame(): noise * scale * std_div(0.001) + 0.5, here kept in 16 bit
            v = np.clip(g * (scale * 0.001 * amp) + 0.5, 0, 1)
            # 8 bit like the tool's own export (generate_grain_frame); noise std is ~20 code values, so
            # quantisation is irrelevant and the pipe carries half the bytes of rgb48
            self.frames.append((v * 255 + 0.5).astype(np.uint8).tobytes())

    def feed(self, pipe):
        try:
            for i in range(self.n):
                pipe.write(self.frames[i % len(self.frames)])
        except (BrokenPipeError, ValueError):
            pass
        finally:
            try:
                pipe.close()
            except Exception:
                pass


def build_graph(look_name, lut, grain, halation, w, h, scale_to=None, split=False, hal_threshold=0.45,
                hal_radius=0.04):
    """Returns (filter_complex, needs_plate)."""
    meta = looks().get(look_name, {}) if look_name else {}
    files = meta.get("files", {})
    fc = f"[0:v]{TO_RGB}[src];"
    cur = "src"
    if split:
        fc += "[src]split[orig][g0];"
        cur = "g0"
    if halation > 0:
        fc += f"[{cur}]split[hs][hsrc];"
        fc += halation_glow("hsrc", "halo", w, hal_threshold, hal_radius)
        cur = "hs"
    need_plate = False
    if grain > 0 and all(k in files and lut_path(files[k]).exists() for k in ("neg", "grain", "print")):
        neg, gr, pr = (lut_path(files[k]) for k in ("neg", "grain", "print"))
        fc += (f"[{cur}]lut3d=file='{esc(neg)}':interp=tetrahedral,split[n0][n1];"
               f"[n1]lut3d=file='{esc(gr)}':interp=tetrahedral,split[g1][g2];"
               f"[g2]colorchannelmixer=rr=0.5:gg=0.5:bb=0.5[gh];"
               f"[1:v]format=gbrp16le[plate];"
               f"[plate][g1]blend=all_mode=multiply:shortest=1[gp];"   # O * G
               f"[gp][gh]blend=all_mode=grainextract[gd];"             # O*G - G/2 + 0.5
               f"[n0][gd]blend=all_mode=grainmerge[ng];"               # N + (O-0.5)*G
               f"[ng]lut3d=file='{esc(pr)}':interp=tetrahedral[graded];")
        need_plate = True
    else:
        if grain > 0:
            print("  (no split LUTs for this look: grain skipped)", file=sys.stderr)
        lut = lut or lut_path(files["full"])
        if not Path(lut).exists():
            sys.exit(f"{lut} missing: generate the LUTs with bash scripts/setup_looks.sh")
        fc += f"[{cur}]lut3d=file='{esc(lut)}':interp=tetrahedral[graded];"
    if halation > 0:
        fc += f"[graded][halo]blend=all_mode=screen:all_opacity={halation}[gradedH];"
    gname = "gradedH" if halation > 0 else "graded"
    if split:
        # before | after: left half original, right half graded, 3 px divider
        fc += (f"[orig]crop=iw/2:ih:0:0[L];[{gname}]crop=iw/2:ih:iw/2:0[R];[L][R]hstack,"
               f"drawbox=x=iw/2-2:y=0:w=4:h=ih:color=white@0.9:t=fill[graded2];")
        cur = "graded2"
    else:
        cur = gname
    sc = f"scale={scale_to}:flags=lanczos," if scale_to else ""
    fc += f"[{cur}]{sc}{TO_YUV}[out]"
    return fc, need_plate


def render(inp, out, look=None, lut=None, grain=0.0, halation=0.0, ss=None, t=None, scale_to=None,
           split=False, crf=16, still_at=None, film="35mm", grain_um=6.0, audio=True, preset="medium",
           hal_threshold=0.45, hal_radius=0.04):
    info = probe(inp)
    meta = looks().get(look, {}) if look else {}
    fc, need_plate = build_graph(look, lut, grain, halation, info["w"], info["h"], scale_to, split,
                                 hal_threshold, hal_radius)
    cmd = ["ffmpeg", "-v", "error", "-stats", "-y"]
    seek = []
    if still_at is not None:
        seek = ["-ss", str(still_at)]
    elif ss is not None:
        seek = ["-ss", str(ss)]
    cmd += seek + (["-t", str(t)] if t and still_at is None else []) + ["-i", str(inp)]
    plate = None
    if need_plate:
        dur = t if t else max(0.0, info["dur"] - (ss or 0))
        nfr = 1 if still_at is not None else int(dur * info["fps"]) + 8
        plate = GrainPlate(info["w"], info["h"], mono=meta.get("bw", False), amp=grain, n_frames=nfr,
                           frame_mm=FILM_MM.get(film, 24.89), grain_um=grain_um)
        cmd += ["-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{info['w']}x{info['h']}",
                "-r", f"{info['fps']:.5f}", "-i", "pipe:0"]
    cmd += ["-filter_complex", fc, "-map", "[out]"]
    if still_at is not None:
        cmd += ["-frames:v", "1", "-update", "1", str(out)]
    else:
        if audio and info["audio"] and not split:
            cmd += ["-map", "0:a?", "-c:a", "copy"]
        cmd += ["-c:v", "libx264", "-threads", X264_THREADS, "-preset", preset, "-crf", str(crf), "-pix_fmt", "yuv420p", *TAGS,
                "-g", str(max(1, round(info["fps"]))), "-movflags", "+faststart", str(out)]   # 1 s keyframes: HyperFrames seeks plates
    t0 = time.time()
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE if plate else subprocess.DEVNULL)
    th = None
    if plate:
        th = threading.Thread(target=plate.feed, args=(p.stdin,), daemon=True)
        th.start()
    rc = p.wait()
    if th:
        th.join(timeout=5)
    if rc != 0:
        sys.exit(f"ffmpeg failed ({rc}): {' '.join(cmd)}")
    return dict(seconds=round(time.time() - t0, 1), grain_source=plate.source if plate else None)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    for name in ("apply", "split", "still"):
        s = sub.add_parser(name)
        s.add_argument("inp")
        s.add_argument("out")
        s.add_argument("--look", help="look name from luts/looks.json")
        s.add_argument("--lut", help="any .cube instead of a look (full pipeline only)")
        s.add_argument("--grain", type=float, default=None,
                       help="grain amount, 1 = datasheet RMS on Super 35 (default: the look's own, else 0)")
        s.add_argument("--halation", type=float, default=None, help="halation opacity 0-1 (default: the look's)")
        s.add_argument("--hal-threshold", type=float, default=0.45, help="highlight level that glows (0-1)")
        s.add_argument("--hal-radius", type=float, default=0.04, help="glow sigma as a fraction of width")
        s.add_argument("--film", default="35mm", choices=list(FILM_MM), help="simulated frame size for grain")
        s.add_argument("--grain-um", type=float, default=6.0, help="grain diameter in microns (tool default 6)")
        s.add_argument("--ss", type=float)
        s.add_argument("--t", type=float)
        s.add_argument("--at", type=float, default=0.0, help="still: time of the frame")
        s.add_argument("--scale", help="output size, e.g. 540:960")
        s.add_argument("--crf", type=int, default=16)
        s.add_argument("--no-audio", action="store_true")
    a = ap.parse_args()
    if a.cmd == "list":
        for k, v in looks().items():
            print(f"{k:16s} {v['title']}\n{'':16s} {v['what']}\n{'':16s} film_look defaults: {v.get('film_look') or '-'}")
        return
    if not a.look and not a.lut:
        sys.exit("give --look or --lut")
    fl = looks().get(a.look, {}).get("film_look", {}) if a.look else {}
    grain = a.grain if a.grain is not None else fl.get("grain", 0.0)
    hal = a.halation if a.halation is not None else fl.get("halation", 0.0)
    r = render(a.inp, a.out, look=a.look, lut=a.lut, grain=grain, halation=hal, ss=a.ss, t=a.t,
               scale_to=a.scale, split=a.cmd == "split", crf=a.crf,
               still_at=a.at if a.cmd == "still" else None, film=a.film, grain_um=a.grain_um,
               audio=not a.no_audio, hal_threshold=a.hal_threshold, hal_radius=a.hal_radius)
    print(f"{a.out}: look={a.look or a.lut} grain={grain} halation={hal} in {r['seconds']}s"
          + (f" (grain plate: {r['grain_source']})" if r["grain_source"] else ""))


if __name__ == "__main__":
    main()
